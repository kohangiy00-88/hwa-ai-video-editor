
import os
import re

import psycopg
from psycopg.rows import dict_row


DATABASE_URL = os.getenv("DATABASE_URL")


class CursorResult:
    def __init__(self, cursor, lastrowid=None):
        self._cursor = cursor
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    @property
    def rowcount(self):
        return self._cursor.rowcount


class DatabaseConnection:
    def __init__(self, connection):
        self._connection = connection

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        return self._connection.__exit__(
            exc_type, exc_value, traceback
        )

    def execute(self, sql, params=None):
        sql = sql.replace("?", "%s")

        match = re.match(
            r"\s*INSERT\s+INTO\s+(projects|video_files)\b",
            sql,
            re.IGNORECASE
        )

        lastrowid = None

        if match and "RETURNING" not in sql.upper():
            sql = sql.rstrip().rstrip(";") + " RETURNING id"

        cursor = self._connection.execute(
            sql,
            params or ()
        )

        if match:
            row = cursor.fetchone()
            if row:
                lastrowid = row["id"]

        return CursorResult(cursor, lastrowid)

    def commit(self):
        self._connection.commit()


def get_connection():
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. "
            "Set it in Render Environment."
        )

    connection = psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        connect_timeout=20
    )

    return DatabaseConnection(connection)


def init_db():
    with get_connection() as conn:

        conn.execute("""
            CREATE TABLE IF NOT EXISTS projects (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                name TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'draft',
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS video_files (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                project_id BIGINT NOT NULL,
                original_filename TEXT NOT NULL,
                stored_filename TEXT NOT NULL,
                content_type TEXT,
                size_bytes BIGINT NOT NULL,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                FOREIGN KEY (project_id)
                    REFERENCES projects(id)
                    ON DELETE CASCADE
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_video_files_project_id
            ON video_files(project_id)
        """)

        conn.commit()
